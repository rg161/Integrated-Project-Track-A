#!/usr/bin/env python3
"""Compute simple tracking error metrics from the controller log.

This script reads the CSV file generated by Controller.py and calculates an
approximate position RMSE and heading RMSE relative to the reference trajectory.
It is useful for evaluating how well the controller tracks the desired path.
"""
import csv
import math
import sys


def read_log(path):
    """Read the CSV log and return the header plus all data rows."""
    rows = []
    with open(path, 'r') as f:
        r = csv.reader(f)
        header = next(r)
        for row in r:
            rows.append(row)
    return header, rows


if __name__ == '__main__':
    """Allow callers to override the default log path via a command-line argument."""
    path = '/tmp/controller_log.csv'
    if len(sys.argv) > 1:
        path = sys.argv[1]

    header, rows = read_log(path)

    # If no data is available, exit with a clear message.
    if not rows:
        print('No data in', path)
        sys.exit(1)

    # Accumulate squared tracking errors for both position and heading.
    sum_pos2 = 0.0
    sum_yaw2 = 0.0
    n = 0

    for row in rows:
        # Extract measured pose and reference pose from the CSV log.
        x_hat = float(row[1])
        y_hat = float(row[2])
        th_hat = float(row[3])
        x_ref = float(row[4])
        y_ref = float(row[5])
        th_ref = float(row[6])

        # Compute position error in the global frame.
        dx = x_ref - x_hat
        dy = y_ref - y_hat

        # Compute wrapped heading error using the shortest-angle representation.
        dth = math.atan2(math.sin(th_ref - th_hat), math.cos(th_ref - th_hat))

        # Sum squared errors so the RMSE can be computed.
        sum_pos2 += dx * dx + dy * dy
        sum_yaw2 += dth * dth
        n += 1

    # RMSE is the square root of the mean squared error.
    rmse_pos = math.sqrt(sum_pos2 / n)
    rmse_yaw = math.sqrt(sum_yaw2 / n)

    print(f"Samples: {n}")
    print(f"Position RMSE: {rmse_pos:.4f} m")
    print(f"Heading RMSE: {rmse_yaw:.4f} rad")
